/**
 * Build the single-file Client module from src/*.js.
 *
 * The DSH Web Client loads one ESM-shaped module per plugin: the loader factory gets
 * `require('react')` and returns `{ inject, apply }`. We keep the sources split by
 * ownership for editing, then concatenate them into that factory body.
 *
 * Usage:
 *   node scripts/build.mjs --check   syntax + manifest + policy checks only
 *   node scripts/build.mjs           checks, then writes client.js
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = [
  'src/art-core.js',
  'src/art-city.js',
  'src/art-building.js',
  'src/art-room.js',
  'src/model.js',
  'src/strings.js',
  'src/render.js',
  'src/ui.js',
  'src/app.js',
];
const PACKAGE_ID = 'dsh-pixel-office';
const CHECK_ONLY = process.argv.includes('--check');

const failures = [];
function fail(message) {
  failures.push(message);
}

for (const relative of SOURCES) {
  const absolute = resolve(ROOT, relative);
  if (!existsSync(absolute)) {
    fail(`missing source: ${relative}`);
    continue;
  }
  const text = readFileSync(absolute, 'utf8');
  try {
    execFileSync(process.execPath, ['--check', absolute], { stdio: 'pipe' });
  } catch (error) {
    const detail = String(error.stderr || error.message || '').split('\n').slice(0, 8).join('\n');
    fail(`syntax error in ${relative}:\n${detail}`);
  }
  // Policy: the Client bundle may import only React and the declared Client
  // primitives package. Harness Client packages other than the ones listed in
  // package.json dsh.client.external must not be required.
  const ALLOWED_REQUIRES = new Set(['react', '@deepseek-ai/dsh-client-ui-primitives']);
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (/^import\s/.test(trimmed) || /^export\s/.test(trimmed)) {
      fail(`top-level ESM import/export is not allowed in ${relative}: ${trimmed.slice(0, 80)}`);
    }
    const required = trimmed.match(/require\(\s*['"]([^'"]+)['"]\s*\)/);
    if (required && !ALLOWED_REQUIRES.has(required[1])) {
      fail(`unexpected require() in ${relative}: ${trimmed.slice(0, 80)}`);
    }
  }
}

for (const manifest of ['package.json', 'locale/en.json', 'locale/zh.json']) {
  const absolute = resolve(ROOT, manifest);
  try {
    JSON.parse(readFileSync(absolute, 'utf8'));
  } catch (error) {
    fail(`invalid JSON in ${manifest}: ${error.message}`);
  }
}

if (failures.length > 0) {
  console.error(`build check failed (${failures.length}):`);
  for (const message of failures) console.error(`- ${message}`);
  process.exit(1);
}

if (CHECK_ONLY) {
  console.log(`build check ok: ${SOURCES.length} sources, manifests valid`);
  process.exit(0);
}

const body = SOURCES.map((relative) => {
  const text = readFileSync(resolve(ROOT, relative), 'utf8').replace(/^\uFEFF/, '');
  const name = relative.split('/').pop();
  return `// ===== ${name} =====\n${text.trimEnd()}\n`;
}).join('\n');

const wrapper = `/**
 * dsh-pixel-office — generated by scripts/build.mjs. Do not edit by hand.
 */
window.__ModuleLoader__.load({
  id: '${PACKAGE_ID}',
  factory(require) {
    const React = require('react');
    const { useCallback, useEffect, useMemo, useRef, useState, useSyncExternalStore } = React;
    const h = React.createElement;

${body}
    return { inject, apply };
  },
});
`;

const target = resolve(ROOT, 'client.js');
writeFileSync(target, wrapper, 'utf8');
console.log(`wrote client.js (${Buffer.byteLength(wrapper)} bytes, ${wrapper.split('\n').length} lines)`);
